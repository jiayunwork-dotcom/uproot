def test_read_failure_during_basket_copy(tmp_path):
    source_filename = tmp_path / "source.root"
    dest_filename = tmp_path / "dest.root"
    with uproot.recreate(source_filename) as f:
        f["note"] = "keep me"
        tree = f.mktree("tree", {"x": np.int32, "y": np.float64})
        tree.extend(
            {"x": np.arange(4, dtype=np.int32), "y": np.linspace(0, 1, 4)}
        )

    with uproot.open(source_filename) as probe:
        y_seek = int(probe["tree"]["y"].member("fBasketSeek")[0])
        y_bytes = int(probe["tree"]["y"].member("fBasketBytes")[0])

    with uproot.open(source_filename) as source:
        # fail only inside the payload of the second branch's basket, past the
        # header window that validation reads: the failure happens mid-copy,
        # after the first branch's baskets have already been moved
        source.file._source = FailingSource(
            source.file._source, y_seek + y_bytes - 10, y_seek + y_bytes
        )
        with uproot.recreate(dest_filename) as dest:
            with pytest.raises(OSError, match="injected read failure"):
                dest.copy_from(source)

    # the source file is untouched
    with uproot.open(source_filename) as source:
        assert source["tree"].num_entries == 4

    # the destination closes and reopens normally; the failed tree never
    # became a readable key, and the object copied before it survived
    with uproot.open(dest_filename) as f:
        assert "tree" not in f.keys()
        assert str(f["note"]) == "keep me"


def test_write_failure_during_basket_copy(tmp_path):
    source_filename = tmp_path / "source.root"
    with uproot.recreate(source_filename) as f:
        f["note"] = "keep me"
        tree = f.mktree("tree", {"x": np.int32, "y": np.float64})
        tree.extend(
            {"x": np.arange(4, dtype=np.int32), "y": np.linspace(0, 1, 4)}
        )

    # calibrate the number of sink.write calls in a full copy
    with uproot.open(source_filename) as source:
        with uproot.recreate(tmp_path / "cal.root") as dest:
            counter = FailingSink(dest._file.sink, 10**12)
            dest._file._sink = counter
            dest.copy_from(source)
            total_writes = counter.calls

    assert total_writes > 0
    raised = 0
    for n in range(total_writes):
        dest_filename = tmp_path / f"dest{n}.root"
        with uproot.open(source_filename) as source:
            with uproot.recreate(dest_filename) as dest:
                # fail on the (n+1)-th write
                dest._file._sink = FailingSink(dest._file.sink, n)
                with pytest.raises(OSError, match="injected write failure"):
                    dest.copy_from(source)
                raised += 1
        # every failed copy leaves a file that closes and reopens cleanly;
        # any tree that appears is complete, and preexisting cycles are intact
        with uproot.open(dest_filename) as f:
            if "tree" in f.keys():
                assert f["tree"].num_entries == 4
                assert f["tree"]["x"].array(library="np").tolist() == [0, 1, 2, 3]
            if "note" in f.keys():
                assert str(f["note"]) == "keep me"
    assert raised == total_writes


def test_copy_without_decompression_or_interpretation(tmp_path):
    source_filename = tmp_path / "source.root"
    dest_filename = tmp_path / "dest.root"
    with uproot.recreate(source_filename, compression=uproot.ZLIB(4)) as f:
        tree = f.mktree("tree", {"x": np.int32, "j": "var * float64"})
        tree.extend(
            {
                "x": np.arange(100, dtype=np.int32),
                "j": ak.Array([[float(i)] * i for i in range(100)]),
            }
        )

    def boom_decompress(*args, **kwargs):
        raise AssertionError("decompression was called during copy_from")

    def boom_basket_array(*args, **kwargs):
        raise AssertionError("array interpretation was called during copy_from")

    original_decompress = uproot.compression.decompress
    original_np = uproot.interpretation.numerical.AsDtype.basket_array
    original_jag = uproot.interpretation.jagged.AsJagged.basket_array
    uproot.compression.decompress = boom_decompress
    uproot.interpretation.numerical.AsDtype.basket_array = boom_basket_array
    uproot.interpretation.jagged.AsJagged.basket_array = boom_basket_array
    try:
        with uproot.open(source_filename) as source:
            with uproot.recreate(dest_filename) as dest:
                dest.copy_from(source)
    finally:
        uproot.compression.decompress = original_decompress
        uproot.interpretation.numerical.AsDtype.basket_array = original_np
        uproot.interpretation.jagged.AsJagged.basket_array = original_jag

    # with the probes removed, the copied data read back correctly
    with uproot.open(dest_filename) as f:
        tree = f["tree"]
        assert tree.num_entries == 100
        assert tree["x"].array(library="np").tolist() == list(range(100))
        assert all(len(row) == i for i, row in enumerate(tree["j"].array(library="np")))


def test_io_requests_are_bounded(tmp_path):
    source_filename = tmp_path / "source.root"
    dest_filename = tmp_path / "dest.root"
    rng = np.random.default_rng(42)
    big = rng.integers(0, 2**31, size=900_000, dtype=np.int32)  # ~3.4 MiB baskets
    with uproot.recreate(source_filename) as f:
        tree = f.mktree("tree", {"x": np.int32, "y": np.int32})
        tree.extend({"x": big, "y": big})
        tree.extend({"x": big[:100], "y": big[:100]})

    with uproot.open(source_filename) as source:
        recording_source = RecordingSource(source.file._source)
        source.file._source = recording_source
        with uproot.recreate(dest_filename) as dest:
            recording_sink = RecordingSink(dest._file._sink)
            dest._file._sink = recording_sink
            dest.copy_from(source)

    assert recording_source.reads, "expected some read requests"
    assert recording_sink.writes, "expected some write requests"
    assert all(stop - start <= ONE_MIB for start, stop in recording_source.reads)
    assert all(num_bytes <= ONE_MIB for _, num_bytes in recording_sink.writes)
    # no unbounded (whole-payload) request happened
    payload_bytes = 2 * (big.nbytes + big[:100].nbytes)
    assert all(stop - start < payload_bytes for start, stop in recording_source.reads)

    with uproot.open(dest_filename) as f:
        assert np.array_equal(
            f["tree"]["x"].array(library="np"), np.concatenate([big, big[:100]])
        )


def test_resident_memory_is_bounded(tmp_path):
    tracemalloc = pytest.importorskip("tracemalloc")
    rng = np.random.default_rng(7)

    def make_source(filename, num_entries):
        data = rng.integers(0, 2**63, size=num_entries, dtype=np.int64)
        with uproot.recreate(filename) as f:
            f.mktree("tree", {"x": np.int64}).extend({"x": data})
        return data

    def peak_of_copy(source_filename, dest_filename):
        tracemalloc.start()
        try:
            with uproot.open(source_filename) as source:
                with uproot.recreate(dest_filename) as dest:
                    dest.copy_from(source)
            return tracemalloc.get_traced_memory()[1]
        finally:
            tracemalloc.stop()

    make_source(tmp_path / "small.root", 1_000)  # ~8 kB payload
    peak_small = peak_of_copy(tmp_path / "small.root", tmp_path / "small-d.root")

    big = make_source(tmp_path / "big.root", 8_000_000)  # ~61 MiB payload
    peak_big = peak_of_copy(tmp_path / "big.root", tmp_path / "big-d.root")

    # the peak does not scale with the payload: well under 4 MiB of payload
    # buffers plus fixed overhead, for both tiers
    assert peak_small < 4 * ONE_MIB
    assert peak_big < 4 * ONE_MIB

    with uproot.open(tmp_path / "big-d.root") as f:
        assert np.array_equal(f["tree"]["x"].array(library="np"), big)


def test_per_branch_compression_is_preserved(tmp_path):
    source_filename = tmp_path / "source.root"
    dest_filename = tmp_path / "dest.root"
    data = {b: np.arange(k * 1000, (k + 1) * 1000, dtype=np.int32) for k, b in enumerate("abc")}
    with uproot.recreate(source_filename) as f:
        tree = f.mktree("t", {"a": np.int32, "b": np.int32, "c": np.int32})
        tree["a"].compression = None
        tree["b"].compression = uproot.ZLIB(4)
        tree["c"].compression = uproot.LZ4(4)
        tree.extend(data)

    before = basket_payloads(source_filename, "t")
    with uproot.open(source_filename) as source:
        with uproot.recreate(dest_filename) as dest:
            dest.copy_from(source)
    after = basket_payloads(dest_filename, "t")

    # different per-branch compression survives as byte-identical payloads
    assert before.keys() == after.keys()
    magics = set()
    for key in before:
        assert before[key]["payload"] == after[key]["payload"]
        magics.add(before[key]["payload"][:2])
    assert len(magics) > 1  # the branches really were compressed differently

    with uproot.open(dest_filename) as f:
        for branch in "abc":
            assert f["t"][branch].array(library="np").tolist() == data[branch].tolist()


def test_branch_fcompress_metadata_is_preserved(tmp_path):
    source_filename = tmp_path / "source.root"
    dest_filename = tmp_path / "dest.root"
    with uproot.recreate(source_filename) as f:
        tree = f.mktree("t", {"a": np.int32, "b": np.int32})
        tree.extend(
            {"a": np.arange(10, dtype=np.int32), "b": np.arange(10, 20, dtype=np.int32)}
        )

    # simulate a ROOT-written file by patching per-branch fCompress values
    with uproot.open(source_filename) as f:
        key = f.key("t")
        meta_start = key.data_cursor.index
        meta_stop = meta_start + key.data_compressed_bytes
    with open(source_filename, "r+b") as fh:
        data = fh.read()
        anchor = struct.pack(">i", 32000)  # fBasketSize follows fCompress
        positions = []
        at = meta_start
        while True:
            at = data.find(anchor, at, meta_stop)
            if at == -1:
                break
            positions.append(at)
            at += 1
        assert len(positions) == 2
        for position, code in zip(positions, (101, 404)):
            fh.seek(position - 4)
            fh.write(struct.pack(">i", code))

    with uproot.open(source_filename) as source:
        assert [source["t"][b].member("fCompress") for b in ("a", "b")] == [101, 404]
        with uproot.recreate(dest_filename) as dest:
            dest.copy_from(source)

    with uproot.open(dest_filename) as f:
        assert [f["t"][b].member("fCompress") for b in ("a", "b")] == [101, 404]
        assert f["t"]["a"].compression == uproot.ZLIB(1)
        assert f["t"]["b"].compression == uproot.LZ4(4)


