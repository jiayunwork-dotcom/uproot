def test_copy_only_latest_cycle(tmp_path):
    source_filename = tmp_path / "source.root"
    dest_filename = tmp_path / "dest.root"
    with uproot.recreate(source_filename) as f:
        f.mktree("t", {"x": np.int32}).extend({"x": np.array([1, 2, 3], dtype=np.int32)})
    with uproot.update(source_filename) as f:
        f.mktree("t", {"x": np.int32}).extend(
            {"x": np.array([4, 5, 6, 7], dtype=np.int32)}
        )

    with uproot.open(source_filename) as source:
        assert source["t;1"].num_entries == 3
        assert source["t;2"].num_entries == 4
        with uproot.recreate(dest_filename) as dest:
            dest.copy_from(source)

    with uproot.open(dest_filename) as f:
        assert f.keys() == ["t;1"]
        assert f["t"].num_entries == 4
        assert f["t"]["x"].array(library="np").tolist() == [4, 5, 6, 7]


def test_no_matches_and_empty_filters(tmp_path):
    source_filename = tmp_path / "source.root"
    dest_filename = tmp_path / "dest.root"
    with uproot.recreate(source_filename) as f:
        f.mktree("t", {"x": np.int32}).extend({"x": np.array([1], dtype=np.int32)})

    with uproot.open(source_filename) as source:
        with uproot.recreate(dest_filename) as dest:
            with pytest.raises(ValueError):
                dest.copy_from(source, filter_name="does-not-exist")
            # require_matches=False makes an empty selection a no-op
            dest.copy_from(source, filter_name="does-not-exist", require_matches=False)
            # a filter that selects only some objects works
