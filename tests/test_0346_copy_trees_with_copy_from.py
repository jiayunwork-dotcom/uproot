def test_copy_two_trees_byte_fidelity(tmp_path):
    source_filename = tmp_path / "source.root"
    dest_filename = tmp_path / "dest.root"
    expected = make_two_trees(source_filename)

    # the destination already has a "placed" object (a histogram) and a tree
    with uproot.recreate(dest_filename) as dest:
        dest["placed"] = np.histogram(np.arange(10))
        dest.mkdir("dir")

    # payloads of the source, located via the basket index *before* copying
    before_tree = basket_payloads(source_filename, "tree")
    before_other = basket_payloads(source_filename, "dir/othertree")

    with uproot.open(source_filename) as source:
        with uproot.recreate(dest_filename) as dest:
            dest["placed"] = np.histogram(np.arange(10, 20))  # preexisting name
            dest.mkdir("dir")
            # tree -> different directory and name; othertree -> over "placed"
            dest.copy_from(
                source,
                rename={"tree": "nested/deep/moved", "dir/othertree": "placed"},
            )

    # payloads of the destination, located via the basket index *after* copying
    after_tree = basket_payloads(dest_filename, "nested/deep/moved")
    after_other = basket_payloads(dest_filename, "placed")

    # the compressed data region of every basket is byte-for-byte identical
    assert before_tree.keys() == after_tree.keys()
    assert before_other.keys() == after_other.keys()
    for key in before_tree:
        assert before_tree[key]["payload"] == after_tree[key]["payload"]
        assert before_tree[key]["fObjlen"] == after_tree[key]["fObjlen"]
        assert before_tree[key]["fKeylen"] == after_tree[key]["fKeylen"]
    for key in before_other:
        assert before_other[key]["payload"] == after_other[key]["payload"]

    # relocated basket keys are self-consistent in the destination
    with uproot.open(dest_filename) as f:
        moved = f["nested/deep/moved"]
        parent_key_location = f["nested/deep"].key("moved").fSeekPdir
        for branch in moved.branches:
            for i in range(branch._num_normal_baskets):
                key = after_tree[branch.name, i]
                assert key["fSeekKey"] == int(branch.member("fBasketSeek")[i])
                assert key["fSeekPdir"] == parent_key_location

    # full read-back against generation-time data, types, titles, counters
    with uproot.open(dest_filename) as f:
        for treename, chunks in (
            ("nested/deep/moved", expected["tree"]),
            ("placed", expected["dir/othertree"]),
        ):
            tree = f[treename]
            assert tree.title == ("first tree" if "moved" in treename else "second tree")
            assert tree.typenames() == {
                "x": "int32_t",
                "b": "bool",
                "v": "double[3]",
                "nj": "int32_t",
                "j": "int32_t[]",
            }
            num_entries = sum(len(chunk["x"]) for chunk in chunks)
            assert tree.num_entries == num_entries
            arrays = tree.arrays(library="np")
            assert np.array_equal(arrays["x"], expected_numpy(chunks, "x"))
            assert np.array_equal(arrays["b"], expected_numpy(chunks, "b"))
            assert np.array_equal(arrays["v"], expected_numpy(chunks, "v"))
            assert arrays["x"].dtype == np.int32
            assert arrays["b"].dtype == np.bool_
            assert arrays["v"].dtype == np.float64
            assert arrays["v"].shape == (num_entries, 3)
            # the count branch is part of the copied tree
            assert np.array_equal(arrays["nj"], expected_counter(chunks))
            assert arrays["nj"].dtype == np.int32
            # variable-length content, including empty lists, in order
            assert [list(row) for row in arrays["j"]] == expected_jagged(chunks, "j")
            # the counter relationship survived the copy
            leaf_count = (
                f[treename]["j"].member("fLeaves")[0].member("fLeafCount")
            )
            assert leaf_count.member("fName") == "nj"
            # branch titles are preserved
            assert f[treename]["x"].title == "x/I"
            assert f[treename]["v"].title == "v[3]/D"
            assert f[treename]["j"].title == "j[nj]/I"

        # "placed" was a histogram at cycle 1; the copied tree is cycle 2
        assert f.classnames()["placed;1"] == "TH1D"
        assert f.classnames()["placed;2"] == "TTree"
        assert f["placed;1"].values().sum() == 10  # the original histogram


