def basket_payloads(filename, treename):
    """
    Uses each branch's basket index (fBasketSeek/fBasketBytes) to locate every
    basket's TKey and returns ``{(branch_name, basket_num): dict}`` with the
    raw compressed data region (all bytes after fKeylen) and the key fields.
    """
    out = {}
    with uproot.open(filename) as f:
        tree = f[treename]
        for branch in tree.branches:
            fBasketSeek = branch.member("fBasketSeek")
            fBasketBytes = branch.member("fBasketBytes")
            for i in range(branch._num_normal_baskets):
                seek, num_bytes = int(fBasketSeek[i]), int(fBasketBytes[i])
                raw = bytes(f.file.source.chunk(seek, seek + num_bytes).raw_data)
                (
                    fNbytes,
                    fVersion,
                    fObjlen,
                    fDatime,
                    fKeylen,
                    fCycle,
                ) = struct.unpack(">ihiIhh", raw[:18])
                if fVersion >= 1000:
                    fSeekKey, fSeekPdir = struct.unpack(">qq", raw[18:34])
                else:
                    fSeekKey, fSeekPdir = struct.unpack(">ii", raw[18:26])
                out[branch.name, i] = {
                    "payload": raw[fKeylen:],
                    "fNbytes": fNbytes,
                    "fObjlen": fObjlen,
                    "fKeylen": fKeylen,
                    "fDatime": fDatime,
                    "fCycle": fCycle,
                    "fSeekKey": fSeekKey,
                    "fSeekPdir": fSeekPdir,
                }
    return out


def make_two_trees(filename):
    """
    Writes two TTrees with identical branch names but different content
    (integer, boolean, fixed-shape vector, variable-length, empty values,
    several extends) and returns the generation-time data for comparison.
    """
    spec = {
        "x": np.int32,
        "b": np.bool_,
        "v": np.dtype((">f8", (3,))),
        "j": "var * int32",
    }
    chunks1 = [
        {
            "x": np.arange(5, dtype=np.int32),
            "b": np.array([True, False, True, False, True]),
            "v": np.arange(15, dtype=np.float64).reshape(5, 3),
            "j": ak.Array([[1, 2], [], [3], [4, 5, 6], []]),
        },
        {  # an extend with zero entries: empty basket content
            "x": np.arange(5, 5, dtype=np.int32),
            "b": np.array([], dtype=np.bool_),
            "v": np.empty((0, 3), dtype=np.float64),
            "j": ak.Array([[]])[:0],
        },
        {
            "x": np.arange(5, 8, dtype=np.int32),
            "b": np.array([False, True, True]),
            "v": np.arange(15, 24, dtype=np.float64).reshape(3, 3),
            "j": ak.Array([[], [7, 8], [9]]),
        },
    ]
    chunks2 = [
        {
            "x": np.arange(-3, 1, dtype=np.int32),
            "b": np.array([False, False, True, True]),
            "v": -np.arange(12, dtype=np.float64).reshape(4, 3),
            "j": ak.Array([[10, 20, 30], [40], [], []]),
        },
        {
            "x": np.arange(1, 3, dtype=np.int32),
            "b": np.array([True, True]),
            "v": -np.arange(12, 18, dtype=np.float64).reshape(2, 3),
            "j": ak.Array([[50], [60, 70]]),
        },
    ]
    with uproot.recreate(filename) as f:
        tree1 = f.mktree("tree", spec, title="first tree")
        for chunk in chunks1:
            tree1.extend(chunk)
        tree2 = f.mktree("dir/othertree", spec, title="second tree")
        for chunk in chunks2:
            tree2.extend(chunk)
    return {"tree": chunks1, "dir/othertree": chunks2}


def expected_numpy(chunks, branch):
    return np.concatenate([chunk[branch] for chunk in chunks])


def expected_counter(chunks):
    # the "nj" count branch is generated by mktree from the jagged "j" data
    return np.concatenate(
        [
            np.array([len(row) for row in chunk["j"]], dtype=np.int32)
            for chunk in chunks
        ]
    )


def expected_jagged(chunks, branch):
    return [row for chunk in chunks for row in chunk[branch].tolist()]


class RecordingSource:
    """Wraps a chunk.Source and records every (start, stop) read request."""

    def __init__(self, wrapped):
        self._wrapped = wrapped
        self.reads = []

    def __getattr__(self, name):
        return getattr(self._wrapped, name)

    def chunk(self, start, stop):
        self.reads.append((start, stop))
        return self._wrapped.chunk(start, stop)

    def chunks(self, ranges, notifications):
        self.reads.extend((start, stop) for start, stop in ranges)
        return self._wrapped.chunks(ranges, notifications)


class RecordingSink:
    """Wraps a FileSink and records every (location, num_bytes) write."""

    def __init__(self, wrapped):
        self._wrapped = wrapped
        self.writes = []

    def __getattr__(self, name):
        return getattr(self._wrapped, name)

    def write(self, location, serialization):
        self.writes.append((location, len(serialization)))
        return self._wrapped.write(location, serialization)


class FailingSource:
    """Wraps a chunk.Source and raises OSError for reads intersecting a range."""

    def __init__(self, wrapped, fail_start, fail_stop):
        self._wrapped = wrapped
        self._fail_start = fail_start
        self._fail_stop = fail_stop

    def __getattr__(self, name):
        return getattr(self._wrapped, name)

    def chunk(self, start, stop):
        if start < self._fail_stop and self._fail_start < stop:
            raise OSError("injected read failure")
        return self._wrapped.chunk(start, stop)

    def chunks(self, ranges, notifications):
        return self._wrapped.chunks(ranges, notifications)


class FailingSink:
    """Wraps a FileSink and raises OSError on the Nth write call."""

    def __init__(self, wrapped, fail_after):
        self._wrapped = wrapped
        self._fail_after = fail_after
        self.calls = 0

    def __getattr__(self, name):
        return getattr(self._wrapped, name)

    def write(self, location, serialization):
        self.calls += 1
        if self.calls > self._fail_after:
            raise OSError("injected write failure")
        return self._wrapped.write(location, serialization)


